@dataclass(frozen=True, slots=True)
class RiskFinding:
    code: RiskReason
    evidence: Mapping
    finding_identity: str = field(init=False)

    def __post_init__(self):
        require(self.code, RiskReason, "reason code")
        object.__setattr__(self, "evidence", freeze_evidence(self.evidence))
        seal(self, "finding", "finding_identity")

    @property
    def category(self):
        return self.code.category
